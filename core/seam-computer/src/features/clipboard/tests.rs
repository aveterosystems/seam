use super::*;

fn types(t: &[&str]) -> Vec<String> {
    t.iter().map(|s| s.to_string()).collect()
}

/// SR-10-03: Open only for a clip that is exactly one web address.
#[test]
fn only_a_whole_web_address_can_be_opened() {
    assert!(openable_url("https://example.com/a?b=c").is_some());
    assert!(openable_url("http://example.com").is_some());
    for bad in [
        "https://looks-safe.example https://evil.example",
        "https://example.com\nhttps://evil.example",
        " https://example.com",
        "file:///etc/passwd",
        "javascript:alert(1)",
        "myapp://do-something",
        "https:///no-host",
        "ZK4 9QP",
    ] {
        assert!(openable_url(bad).is_none(), "{bad}");
    }
}

/// SR-4-06: a copied file is never sent as text.
#[test]
fn files_are_not_sent_as_text() {
    assert!(!sendable(&types(&[
        "public.file-url",
        "public.utf8-plain-text"
    ])));
    assert!(!sendable(&types(&["NSFilenamesPboardType"])));
    assert!(!sendable(&types(&[
        "public.utf8-plain-text",
        "org.nspasteboard.AutoGeneratedType"
    ])));
    assert!(sendable(&types(&["public.utf8-plain-text", "public.html"])));
}

#[test]
fn password_manager_items_are_never_sent() {
    assert!(is_private(&types(&[
        "public.utf8-plain-text",
        "org.nspasteboard.ConcealedType"
    ])));
    assert!(is_private(&types(&["org.nspasteboard.TransientType"])));
    assert!(!is_private(&types(&[
        "public.utf8-plain-text",
        "public.html"
    ])));
}

const T0: i64 = 1_000_000_000;

/// SR-4-03: a copy held while offline.
#[test]
fn sends_the_latest_when_the_phone_is_back() {
    let mut q = ClipQueue::default();
    q.hold("old", T0);
    q.hold("new", T0 + 1000);
    assert_eq!(q.take(T0 + 5000, true), Some("new"));
    assert!(q.is_empty());
}

#[test]
fn never_sends_after_sync_is_turned_off() {
    let mut q = ClipQueue::default();
    q.hold("x", T0);
    assert_eq!(q.take(T0 + 5000, false), None);
    assert!(q.is_empty(), "and doesn't keep it for later either");
}

#[test]
fn clearing_for_a_new_phone_drops_it() {
    let mut q = ClipQueue::default();
    q.hold("for the old phone", T0);
    q.clear();
    assert_eq!(q.take(T0 + 5000, true), None);
}

#[test]
fn a_stale_copy_is_dropped() {
    let mut q = ClipQueue::default();
    q.hold("x", T0);
    assert_eq!(q.take(T0 + HOLD_MS + 1000, true), None);
}

/// Rule 6: what was copied never reaches a log, even through a debug print.
#[test]
fn a_clip_never_prints_its_text() {
    let clip = Clip {
        text: "hunter2".into(),
        at: 1,
        from_phone: true,
    };
    assert!(!format!("{clip:?}").contains("hunter2"));
    let item = PasteboardItem {
        types: types(&["public.utf8-plain-text"]),
        text: Some("hunter2".into()),
    };
    assert!(!format!("{item:?}").contains("hunter2"));
}
