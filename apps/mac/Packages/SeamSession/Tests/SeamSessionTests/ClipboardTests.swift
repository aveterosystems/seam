@testable import SeamSession

struct ClipRulesTests {
    private let t0 = Date(timeIntervalSince1970: 1_000_000)

    @Test func sendsNewCopiesOnce() {
        var r = ClipRules()
        #expect(r.outgoing("a", now: t0) == "a")
        #expect(r.outgoing("a", now: t0 + 0.5) == nil) // the same change seen twice
        #expect(r.outgoing("b", now: t0 + 0.6) == "b")
        #expect(r.outgoing("a", now: t0 + 0.7) == "a") // copying it again later still sends it
    }

    /// SR-4-10: a copy that failed to send isn't blocked as a duplicate for good.
    @Test func aCopyThatFailedToSendGoesWhenCopiedAgain() {
        var r = ClipRules()
        #expect(r.outgoing("a", now: t0) == "a")
        #expect(r.outgoing("a", now: t0 + ClipRules.repeatWindow) == "a")
    }

    /// SR-10-03: Open only for a clip that is exactly one web address.
    @Test func onlyAWholeWebAddressCanBeOpened() {
        #expect(ClipRules.openableURL("https://example.com/a?b=c") != nil)
        #expect(ClipRules.openableURL("http://example.com") != nil)
        #expect(ClipRules.openableURL("https://looks-safe.example https://evil.example") == nil)
        #expect(ClipRules.openableURL("https://example.com\nhttps://evil.example") == nil)
        #expect(ClipRules.openableURL(" https://example.com") == nil)
        #expect(ClipRules.openableURL("file:///etc/passwd") == nil)
        #expect(ClipRules.openableURL("javascript:alert(1)") == nil)
        #expect(ClipRules.openableURL("myapp://do-something") == nil)
        #expect(ClipRules.openableURL("https:///no-host") == nil)
        #expect(ClipRules.openableURL("ZK4 9QP") == nil)
    }

    /// SR-4-06: a copied file is never sent as text.
    @Test func filesAreNotSentAsText() {
        #expect(!ClipRules.sendable(types: ["public.file-url", "public.utf8-plain-text"]))
        #expect(!ClipRules.sendable(types: ["NSFilenamesPboardType"]))
        #expect(!ClipRules.sendable(types: ["public.utf8-plain-text", "org.nspasteboard.AutoGeneratedType"]))
        #expect(ClipRules.sendable(types: ["public.utf8-plain-text", "public.html"]))
    }

    @Test func neverEchoesWhatThePhoneSent() {
        var r = ClipRules()
        #expect(r.incoming("from phone") == "from phone")
        #expect(r.outgoing("from phone") == nil)
        #expect(r.outgoing("mine") == "mine")
    }

    @Test func skipsEmptyAndOversized() {
        var r = ClipRules(maxBytes: 4)
        #expect(r.outgoing(nil) == nil)
        #expect(r.outgoing("") == nil)
        #expect(r.outgoing("12345") == nil)
        #expect(r.incoming("12345") == nil)
        #expect(r.outgoing("ééé") == nil) // bytes, not characters
        #expect(r.outgoing("1234") == "1234")
    }

    @Test func passwordManagerItemsAreNeverSent() {
        #expect(ClipRules.isPrivate(types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]))
        #expect(ClipRules.isPrivate(types: ["org.nspasteboard.TransientType"]))
        #expect(!ClipRules.isPrivate(types: ["public.utf8-plain-text", "public.html"]))
    }
}

/// SR-4-03: a copy held while offline.
struct ClipQueueTests {
    private let t0 = Date(timeIntervalSince1970: 1_000_000)

    @Test func sendsTheLatestWhenThePhoneIsBack() {
        var q = ClipQueue<String>()
        q.hold("old", at: t0)
        q.hold("new", at: t0 + 1)
        #expect(q.take(now: t0 + 5, syncOn: true) == "new")
        #expect(q.isEmpty)
    }

    @Test func neverSendsAfterSyncIsTurnedOff() {
        var q = ClipQueue<String>()
        q.hold("x", at: t0)
        #expect(q.take(now: t0 + 5, syncOn: false) == nil)
        #expect(q.isEmpty) // and doesn't keep it for later either
    }

    @Test func clearingForANewPhoneDropsIt() {
        var q = ClipQueue<String>()
        q.hold("for the old phone", at: t0)
        q.clear()
        #expect(q.take(now: t0 + 5, syncOn: true) == nil)
    }

    @Test func aStaleCopyIsDropped() {
        var q = ClipQueue<String>()
        q.hold("x", at: t0)
        #expect(q.take(now: t0 + ClipQueue<String>.maxAge + 1, syncOn: true) == nil)
    }
}

struct AdbSetupTests {
    /// SR-4-11: the user agrees to every change the setup makes.
    @Test func consentListsEveryChange() {
        let consent = AdbSetup.consent
        #expect(consent.contains("system log"))
        #expect(consent.contains("over other apps"))
        #expect(consent.contains("restarts"))
        #expect(AdbSetup.steps(serial: "x").filter { $0.grants != nil }.count == 3)
        // Decision 0005: no battery-optimisation exemption any more
        #expect(!AdbSetup.steps(serial: "x").contains { $0.arguments.contains("deviceidle") })
        #expect(!consent.contains("battery"))
        #expect(AdbSetup.stepTimeout <= 30)
    }

    @Test func findsAdbOnlyInKnownPlaces() {
        #expect(AdbSetup.locate(home: "/Users/m", exists: { $0 == "/usr/local/bin/adb" }) == "/usr/local/bin/adb")
        #expect(AdbSetup.locate(home: "/Users/m", exists: { $0 == "/Users/m/Library/Android/sdk/platform-tools/adb" }) != nil)
        #expect(AdbSetup.locate(home: "/Users/m", exists: { _ in false }) == nil)
    }

    @Test func listsOnlyAuthorisedDevices() {
        let out = "List of devices attached\nR5CX123\tdevice\nemulator-5554\toffline\nR5CY999\tunauthorized\n192.168.1.4:5555\tdevice\n\n"
        #expect(AdbSetup.devices(from: out) == ["R5CX123", "192.168.1.4:5555"])
        #expect(AdbSetup.devices(from: "List of devices attached\n\n").isEmpty)
    }

    @Test func grantsOnlyTheFullBuildAndRestartsIt() {
        let steps = AdbSetup.steps(serial: "R5CX123")
        #expect(steps.allSatisfy { $0.arguments.starts(with: ["-s", "R5CX123", "shell"]) })
        #expect(steps.contains { $0.arguments.suffix(2) == ["com.avetero.seam.full", "android.permission.READ_LOGS"] })
        #expect(steps.contains { $0.arguments.contains("SYSTEM_ALERT_WINDOW") })
        #expect(steps.last?.arguments.contains("com.avetero.seam.full/com.avetero.seam.MainActivity") == true)
    }
}
